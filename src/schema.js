// src/schema.js
// Fixed, local, fictional schema for the workbench.
// Only columns listed here are encrypted; everything else is analytics data.

export const TABLE = "events";

export const COLUMNS = Object.freeze([
  { name: "customer_email", purpose: "pii", label: "客户邮箱" },
  { name: "session_label", purpose: "analytics", label: "会话标签" },
  { name: "audit_ref", purpose: "audit", label: "审计引用" },
]);

export const ENCRYPTED_COLUMNS = Object.freeze(COLUMNS.map((c) => c.name));
export const CLEAR_COLUMNS = Object.freeze([
  "occurred_at",
  "region",
  "plan",
  "revenue_minor",
]);

export const PURPOSE_TO_COLUMN = Object.freeze(
  Object.fromEntries(COLUMNS.map((c) => [c.purpose, c.name])),
);
export const COLUMN_TO_PURPOSE = Object.freeze(
  Object.fromEntries(COLUMNS.map((c) => [c.name, c.purpose])),
);

export const KEY_STATUSES = Object.freeze(["staged", "active", "retiring", "destroyed"]);

export const PURPOSES = Object.freeze(COLUMNS.map((c) => c.purpose));

export const RUN_STATUSES = Object.freeze([
  "running",
  "paused",
  "interrupted",
  "verifying",
  "rolling_back",
  "rollback_interrupted",
  "completed",
  "failed",
  "rolled_back",
]);

/** Statuses that keep the single-live-run slot occupied. */
export const LIVE_RUN_STATUSES = Object.freeze([
  "running",
  "paused",
  "interrupted",
  "verifying",
  "rolling_back",
  "rollback_interrupted",
  "failed",
]);

export function assertColumn(column) {
  if (!COLUMN_TO_PURPOSE[column]) throw new Error(`unknown encrypted column: ${column}`);
  return column;
}

export function assertPurpose(purpose) {
  if (!PURPOSE_TO_COLUMN[purpose]) throw new Error(`unknown purpose: ${purpose}`);
  return purpose;
}

/** Shadow/backup table names are generated by us and validated before SQL use. */
export const SHADOW_TABLE_RE = /^events_shadow_[0-9a-f]{12}$/;
export const BACKUP_TABLE_RE = /^events_backup_[0-9a-f]{12}$/;
